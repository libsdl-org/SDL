#include "SDL_internal.h"

#ifdef SDL_PLATFORM_PUMPKINOS

#include "../SDL_main_callbacks.h"
#include "../../core/pumpkin/SDL_pumpkin.h"

/* SDL_RunApp() for PumpkinOS.

   A PumpkinOS application is a shared library whose PilotMain() entry point
   (generated by SDL_main.h) is called by the launcher on the task thread, so
   there is no command line. When the caller passes no arguments, argv[0] is
   filled with the name of the running application (its PalmOS database name)
   so that main() sees a conventional argument vector. */

int SDL_RunApp(int argc, char *argv[], SDL_main_func mainFunction, void *reserved)
{
    char *app_argv[2];
    const char *name;

    (void)reserved;

    if (argc > 0 && argv) {
        return SDL_CallMainFunction(argc, argv, mainFunction);
    }

    name = pumpkin_get_app_name();
    if (!name || !*name) {
        name = "SDL_app";
    }

    app_argv[0] = (char *)name;
    app_argv[1] = NULL;

    return SDL_CallMainFunction(1, app_argv, mainFunction);
}

#endif // SDL_PLATFORM_PUMPKINOS
